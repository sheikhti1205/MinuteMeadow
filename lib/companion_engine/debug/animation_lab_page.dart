/// Development-only inspection surface for the companion compositor.
///
/// It intentionally ships no production catalogue and no pet artwork: the rig
/// and atlas are generated by [GeometricRigFixture].
class AnimationLabPage extends StatefulWidget {
  const AnimationLabPage({super.key});

  @override
  State<AnimationLabPage> createState() => _AnimationLabPageState();
}

class _AnimationLabPageState extends State<AnimationLabPage>
    with SingleTickerProviderStateMixin, WidgetsBindingObserver {
  CompanionRig? _rig;
  AtlasCache? _atlas;
  RigPlayback? _playback;
  CompanionScene? _scene;
  late final Ticker _ticker;
  Object? _error;

  bool _playing = true;
  int _pixelScale = 2;
  double _speed = 1;
  String _clipId = 'idle';
  bool _showGrid = true;
  bool _showPivots = false;
  bool _showHitboxes = true;
  bool _showLayers = false;
  int _background = 0;
  bool _wasPetting = false;
  bool _lifecycleActive = true;
  bool _tickerModeEnabled = true;
  Duration _lastTick = Duration.zero;
  int _loadGeneration = 0;

  RigManifestInspection? _inspection;
  CompanionRig? _pendingRig;
  RigManifestInspection? _pendingInspection;
  String _sourceLabel = 'geometric fixture';
  String _inspectionSource = 'geometric fixture';
  String? _loadStatus;

  final Set<String> _hiddenLayers = <String>{};
  final Map<String, double> _layerOpacity = <String, double>{};
  final List<String> _log = <String>[];

  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addObserver(this);
    _ticker = createTicker(_onTick);
    _load();
  }

  @override
  void dispose() {
    WidgetsBinding.instance.removeObserver(this);
    _ticker.dispose();
    _atlas?.dispose();
    super.dispose();
  }

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    final enabled = TickerMode.valuesOf(context).enabled;
    if (enabled == _tickerModeEnabled) return;
    _tickerModeEnabled = enabled;
    _lastTick = Duration.zero;
    if (!enabled) {
      if (_ticker.isActive) _ticker.stop();
    } else if (_playing && _lifecycleActive) {
      // A muted ticker keeps its original start time, so restart it to avoid a
      // large elapsed jump on the first frame after unmuting.
      if (_ticker.isActive) _ticker.stop();
      _ticker.start();
    }
  }

  @override
  void didChangeAppLifecycleState(AppLifecycleState state) {
    _lifecycleActive = state == AppLifecycleState.resumed;
    if (_lifecycleActive && _playing && _tickerModeEnabled) {
      _lastTick = Duration.zero;
      if (!_ticker.isActive) _ticker.start();
    } else if (_ticker.isActive) {
      _ticker.stop();
    }
  }

  Future<void> _load() async {
    final generation = ++_loadGeneration;
    if (_error != null) setState(() => _error = null);
    try {
      final bundle = await GeometricRigFixture.create();
      if (!mounted || generation != _loadGeneration) {
        bundle.atlasImage.dispose();
        return;
      }
      final cache = AtlasCache()..put(bundle.atlasId, bundle.atlasImage);
      final previous = _atlas;
      final clipId =
          bundle.rig.defaultClip ??
          (bundle.rig.clips.isEmpty ? null : bundle.rig.clips.keys.first);
      final rawManifest = RigCodec.encode(bundle.rig);
      setState(() {
        _atlas = cache;
        _rig = bundle.rig;
        _scene = _sceneFor(bundle.rig);
        _clipId = clipId ?? '';
        _playback = RigPlayback(
          rig: bundle.rig,
          defaultClip: clipId,
          speed: _speed,
        );
        _inspection = RigManifestInspection.valid(
          raw: rawManifest,
          parsedRig: bundle.rig,
        );
        _inspectionSource = 'geometric fixture';
        _sourceLabel = 'geometric fixture';
        _pendingRig = null;
        _pendingInspection = null;
        _loadStatus = null;
        _error = null;
        _log.clear();
        _wasPetting = false;
      });
      previous?.dispose();
      if (_playing && _lifecycleActive && _tickerModeEnabled && !_ticker.isActive) {
        _lastTick = Duration.zero;
        _ticker.start();
      }
    } catch (error) {
      if (!mounted || generation != _loadGeneration) return;
      setState(() => _error = error);
    }
  }

  CompanionScene _sceneFor(CompanionRig rig) => CompanionScene(
    field: Size(
      math.max(160.0, rig.canvasWidth + 48.0),
      math.max(120.0, rig.canvasHeight + 48.0),
    ),
    companionSize: rig.canvasSize,
  );

  bool _hasAtlases(CompanionRig rig, AtlasCache cache) {
    for (final atlas in rig.atlases.values) {
      final image = cache.image(atlas.id);
      if (image == null ||
          image.width != atlas.width ||
          image.height != atlas.height) {
        return false;
      }
    }
    return true;
  }

  List<String> _missingAtlasIds(CompanionRig rig, AtlasCache cache) => [
    for (final atlas in rig.atlases.values)
      if (!_hasAtlas(atlas, cache)) atlas.id,
  ];

  bool _hasAtlas(AtlasDefinition atlas, AtlasCache cache) {
    final image = cache.image(atlas.id);
    return image != null &&
        image.width == atlas.width &&
        image.height == atlas.height;
  }

  void _applyRig(
    CompanionRig rig, {
    required RigManifestInspection inspection,
    required String sourceLabel,
  }) {
    final cache = _atlas;
    if (cache == null) return;
    cache.retain(rig.atlases.keys.toSet());
    final clipId = rig.defaultClip ??
        (rig.clips.isEmpty ? null : rig.clips.keys.first);
    setState(() {
      _rig = rig;
      _scene = _sceneFor(rig);
      _clipId = clipId ?? '';
      _playback = RigPlayback(
        rig: rig,
        defaultClip: clipId,
        speed: _speed,
      );
      _inspection = inspection;
      _inspectionSource = sourceLabel;
      _sourceLabel = sourceLabel;
      _pendingRig = null;
      _pendingInspection = null;
      _loadStatus = null;
      _hiddenLayers.clear();
      _layerOpacity.clear();
      _log.clear();
      _wasPetting = false;
    });
    _lastTick = Duration.zero;
    if (_playing && _lifecycleActive && _tickerModeEnabled && !_ticker.isActive) {
      _ticker.start();
    }
  }

  void _setSpeed(double value) {
    _playback?.speed = value;
    setState(() => _speed = value);
  }

  void _setFileError(String message) {
    if (!mounted) return;
    setState(() => _loadStatus = message);
  }

  Future<void> _loadManifest() async {
    try {
      final file = await RigFileLoader.pickManifest();
      if (file == null || !mounted) return;
      final raw = await RigFileLoader.readManifestText(file);
      if (!mounted) return;
      final inspection = RigManifestInspection.inspect(raw);
      final rig = inspection.rig;
      if (rig == null) {
        setState(() {
          _inspection = inspection;
          _inspectionSource = file.name;
          _loadStatus =
              'Rejected ${file.name}: ${inspection.issues.length} issue(s)';
        });
        await _showManifestInspector();
        return;
      }
      final cache = _atlas;
      if (cache == null) return;
      if (_hasAtlases(rig, cache)) {
        _applyRig(
          rig,
          inspection: inspection,
          sourceLabel: file.name,
        );
      } else {
        setState(() {
          _inspection = inspection;
          _inspectionSource = file.name;
          _pendingRig = rig;
          _pendingInspection = inspection;
          _loadStatus =
              'Atlas needed: ${_missingAtlasIds(rig, cache).join(', ')}';
        });
      }
    } on RigFileException catch (error) {
      _setFileError(error.message);
    } on Exception {
      _setFileError('Could not load that manifest.');
    }
  }

  Future<void> _loadAtlas() async {
    final candidate = _pendingRig ?? _rig;
    final cache = _atlas;
    if (candidate == null || cache == null) return;
    try {
      final file = await RigFileLoader.pickAtlas();
      if (file == null || !mounted) return;
      final atlasId = RigFileLoader.resolveAtlasId(
        candidate,
        file.name,
        loadedAtlasIds: cache.atlasIds,
      );
      final atlas = candidate.atlases[atlasId];
      if (atlas == null) {
        throw RigFileException('The manifest has no atlas "$atlasId".');
      }
      final bytes = await RigFileLoader.readAtlasBytes(file);
      if (!mounted) return;
      final image = await AtlasCache.decode(bytes);
      if (!mounted) {
        image.dispose();
        return;
      }
      final actualWidth = image.width;
      final actualHeight = image.height;
      if (actualWidth != atlas.width || actualHeight != atlas.height) {
        image.dispose();
        throw RigFileException(
          'Atlas "${atlas.id}" is ${actualWidth}x$actualHeight; '
          'the manifest expects ${atlas.width}x${atlas.height}.',
        );
      }
      cache.put(atlasId, image);
      final pending = _pendingRig;
      final pendingInspection = _pendingInspection;
      if (pending != null &&
          pendingInspection != null &&
          _hasAtlases(pending, cache)) {
        _applyRig(
          pending,
          inspection: pendingInspection,
          sourceLabel: _inspectionSource,
        );
      } else {
        final remaining = _missingAtlasIds(pending ?? candidate, cache);
        setState(() {
          _loadStatus = remaining.isEmpty
              ? 'Loaded atlas ${atlas.id}'
              : 'Loaded atlas ${atlas.id} · still need: '
                    '${remaining.join(', ')}';
        });
      }
    } on RigFileException catch (error) {
      _setFileError(error.message);
    } on Exception {
      _setFileError('Could not load that atlas image.');
    }
  }

  Future<void> _showManifestInspector() async {
    if (!mounted) return;
    final inspection = _inspection;
    if (inspection == null) return;
    await showDialog<void>(
      context: context,
      builder: (context) {
        final rig = inspection.rig;
        final issues = inspection.issues;
        final small = Theme.of(context).textTheme.bodySmall;
        return AlertDialog(
          title: const Text('Rig manifest'),
          content: SizedBox(
            width: 560,
            child: ConstrainedBox(
              constraints: const BoxConstraints(maxHeight: 420),
              child: SingleChildScrollView(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    SelectableText('Source: $_inspectionSource'),
                    const SizedBox(height: 4),
                    SelectableText(
                      rig == null
                          ? 'Invalid · ${issues.length} issue(s)'
                          : 'Valid · schema ${rig.schemaVersion} of '
                                '${CompanionRig.currentSchemaVersion} · '
                                '${rig.layers.length} layers · '
                                '${rig.clips.length} clips',
                    ),
                    if (issues.isNotEmpty) ...[
                      const SizedBox(height: 8),
                      for (final issue in issues)
                        SelectableText(
                          '• $issue',
                          style: small?.copyWith(
                            color: Theme.of(context).colorScheme.error,
                          ),
                        ),
                    ],
                    const Divider(),
                    const Text('Raw manifest'),
                    const SizedBox(height: 4),
                    SelectableText(
                      inspection.raw,
                      style: const TextStyle(
                        fontFamily: 'monospace',
                        fontSize: 11,
                      ),
                    ),
                  ],
                ),
              ),
            ),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.pop(context),
              child: const Text('Close'),
            ),
          ],
        );
      },
    );
  }

  void _onTick(Duration elapsed) {
    final playback = _playback;
    final scene = _scene;
    if (playback == null || scene == null) return;
    final delta = elapsed - _lastTick;
    _lastTick = elapsed;
    if (!_playing || !_lifecycleActive || !_tickerModeEnabled) return;
    if (delta <= Duration.zero) return;
    final events = playback.advance(delta.inMicroseconds / 1000);
    scene.advance(
      Duration(microseconds: (delta.inMicroseconds * _speed).round()),
    );
    for (final event in events) {
      if (event.completed) _logLine('${event.clipId} completed');
    }
    for (final event in scene.takeEvents()) {
      _logLine(_eventLabel(event.type));
    }
    _syncMotion(playback, scene);
    if (mounted) setState(() {});
  }

  void _syncMotion(RigPlayback playback, CompanionScene scene) {
    final petting = scene.motion == CompanionMotion.petting;
    if (petting &&
        !_wasPetting &&
        _clipId != 'pet' &&
        playback.rig.clipById('pet') != null) {
      playback.play('pet');
    }
    _wasPetting = petting;

    final motionClip = switch (scene.motion) {
      CompanionMotion.walking ||
      CompanionMotion.chasing ||
      CompanionMotion.returning => 'walk',
      CompanionMotion.running => 'run',
      CompanionMotion.jumping => 'jump',
      CompanionMotion.idle || CompanionMotion.petting => null,
    };
    for (final id in const ['walk', 'run', 'jump']) {
      if (id == _clipId || playback.rig.clipById(id) == null) continue;
      if (id == motionClip) {
        if (!playback.isPlaying(id)) playback.play(id);
      } else if (playback.isPlaying(id)) {
        playback.stop(id);
      }
    }
  }

  void _setPlaying(bool value) {
    if (_playing == value) return;
    setState(() => _playing = value);
    if (value) {
      _lastTick = Duration.zero;
      if (_lifecycleActive && _tickerModeEnabled && !_ticker.isActive) {
        _ticker.start();
      }
    } else if (_ticker.isActive) {
      _ticker.stop();
    }
  }

  void _selectClip(String id) {
    final rig = _rig;
    if (rig == null) return;
    setState(() {
      _clipId = id;
      _playback = RigPlayback(rig: rig, defaultClip: id, speed: _speed);
      _wasPetting = false;
    });
  }

  void _scrub(double timeMs) {
    _setPlaying(false);
    _playback?.seek(timeMs);
    setState(() {});
  }

  void _step(double deltaMs) {
    final rig = _rig;
    final playback = _playback;
    if (rig == null || playback == null) return;
    _setPlaying(false);
    final duration = rig.clipById(_clipId)?.durationMs.toDouble() ?? 0;
    final current = playback.timeOf(_clipId) ?? 0;
    playback.seek((current + deltaMs).clamp(0.0, duration).toDouble());
    setState(() {});
  }

  void _reset() {
    _scene?.reset();
    _playback?.seek(0);
    _wasPetting = false;
    _logLine('reset');
    setState(() {});
  }

  void _throwDefault() {
    final scene = _scene;
    if (scene == null) return;
    scene.throwBall();
    for (final event in scene.takeEvents()) {
      _logLine(_eventLabel(event.type));
    }
    setState(() {});
  }

  void _runMovementRoute() {
    final scene = _scene;
    if (scene == null) return;
    final home = scene.home;
    final right = scene.field.width - scene.companionSize.width;
    if (!scene.playRoute([
      CompanionMove(
        target: Offset(right * 0.2, home.dy),
        duration: const Duration(milliseconds: 550),
      ),
      CompanionMove(
        target: Offset(right * 0.8, home.dy),
        duration: const Duration(milliseconds: 400),
        gait: CompanionGait.run,
      ),
      CompanionMove(
        target: home,
        duration: const Duration(milliseconds: 420),
        gait: CompanionGait.jump,
      ),
    ])) {
      return;
    }
    if (_playing) {
      setState(() {});
    } else {
      _setPlaying(true);
    }
  }

  Offset _toScene(Offset local) {
    final scene = _scene;
    if (scene == null) return Offset.zero;
    return Offset(
      (local.dx / _pixelScale).clamp(0.0, scene.field.width).toDouble(),
      (local.dy / _pixelScale).clamp(0.0, scene.field.height).toDouble(),
    );
  }

  void _onPointerDown(PointerDownEvent event) {
    final scene = _scene;
    if (scene == null) return;
    final point = _toScene(event.localPosition);
    if (!scene.startPet(point)) {
      scene.throwBall(target: point);
    }
    for (final event in scene.takeEvents()) {
      _logLine(_eventLabel(event.type));
    }
    setState(() {});
  }

  void _onPointerMove(PointerMoveEvent event) {
    final scene = _scene;
    if (scene == null) return;
    scene.updatePet(_toScene(event.localPosition));
    setState(() {});
  }

  void _endPet() {
    final scene = _scene;
    if (scene == null) return;
    scene.endPet();
    setState(() {});
  }

  void _logLine(String message) {
    final now = (_scene?.nowMs ?? 0) / 1000;
    _log.insert(0, '${now.toStringAsFixed(1)}s $message');
    if (_log.length > 7) _log.removeLast();
  }

  static const Map<CompanionSceneEventType, String> _eventLabels =
      <CompanionSceneEventType, String>{
        CompanionSceneEventType.pet: 'pet',
        CompanionSceneEventType.ballThrown: 'ball thrown',
        CompanionSceneEventType.ballBounced: 'ball bounced',
        CompanionSceneEventType.ballRolling: 'ball rolling',
        CompanionSceneEventType.ballCaught: 'ball caught',
        CompanionSceneEventType.ballReturned: 'ball returned',
        CompanionSceneEventType.ballMissed: 'ball missed',
        CompanionSceneEventType.movementCompleted: 'movement completed',
      };

  String _eventLabel(CompanionSceneEventType type) =>
      _eventLabels[type] ?? type.name;

  Affine2 _rootTransform(CompanionScene scene) {
    final rect = scene.companionRect;
    var matrix = Affine2.translation(rect.left, rect.top);
    if (scene.facing < 0) {
      matrix =
          matrix *
          Affine2.translation(rect.width, 0) *
          Affine2.scale(-1, 1);
    }
    return matrix;
  }

  ui.Color? get _backgroundColor => switch (_background) {
    1 => const ui.Color(0xFF211B18),
    2 => const ui.Color(0xFFFFF9EE),
    _ => null,
  };

  @override
  Widget build(BuildContext context) => Scaffold(
    appBar: AppBar(
      title: const Text('Animation lab'),
      actions: [
        IconButton(
          tooltip: 'Manifest',
          icon: const Icon(Icons.description_outlined),
          onPressed: _inspection == null ? null : _showManifestInspector,
        ),
      ],
    ),
    body: SafeArea(child: _body(context)),
  );

  Widget _body(BuildContext context) {
    final error = _error;
    if (error != null) {
      return Center(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              const Text('Could not build the geometric rig.'),
              const SizedBox(height: 8),
              Text('$error', textAlign: TextAlign.center),
              const SizedBox(height: 12),
              FilledButton(onPressed: _load, child: const Text('Try again')),
            ],
          ),
        ),
      );
    }
    if (_rig == null || _atlas == null || _playback == null || _scene == null) {
      return const Center(child: CircularProgressIndicator());
    }
    return Column(
      children: [
        Expanded(child: _preview(context)),
        SizedBox(height: 300, child: _controls(context)),
      ],
    );
  }

  Widget _preview(BuildContext context) {
    final rig = _rig!;
    final scene = _scene!;
    final playback = _playback!;
    final pose = buildCompanionPose(
      rig,
      animations: playback.sample(),
      hiddenLayers: _hiddenLayers,
      layerOpacity: <String, double>{
        for (final layer in rig.layers)
          layer.id: _layerOpacity[layer.id] ?? 1,
      },
      rootTransform: _rootTransform(scene),
    );
    final ballQuad = scene.ballQuad(GeometricRigFixture.ballRegion);
    return ColoredBox(
      color: Theme.of(context).colorScheme.surfaceContainerLowest,
      child: SingleChildScrollView(
        child: SingleChildScrollView(
          scrollDirection: Axis.horizontal,
          padding: const EdgeInsets.all(12),
          child: Listener(
            behavior: HitTestBehavior.opaque,
            onPointerDown: _onPointerDown,
            onPointerMove: _onPointerMove,
            onPointerUp: (_) => _endPet(),
            onPointerCancel: (_) => _endPet(),
            child: SpriteStage(
              pose: pose,
              atlas: _atlas!,
              sceneSize: scene.field,
              pixelScale: _pixelScale,
              background: _backgroundColor,
              showGrid: _showGrid,
              showPivots: _showPivots,
              showHitboxes: _showHitboxes,
              hitboxes: scene.hitboxes,
              overlayQuads: ballQuad == null
                  ? const <CompanionQuad>[]
                  : <CompanionQuad>[ballQuad],
            ),
          ),
        ),
      ),
    );
  }

  Widget _controls(BuildContext context) {
    final rig = _rig!;
    final playback = _playback!;
    final scene = _scene!;
    final hasClip = rig.clips.containsKey(_clipId);
    final clip = hasClip ? rig.clipById(_clipId) : null;
    final duration = (clip?.durationMs ?? 1).toDouble();
    final time = hasClip
        ? (playback.timeOf(_clipId) ?? 0).clamp(0.0, duration).toDouble()
        : 0.0;
    final small = Theme.of(context).textTheme.bodySmall;

    return Material(
      color: Theme.of(context).colorScheme.surfaceContainerLow,
      child: SingleChildScrollView(
        padding: const EdgeInsets.fromLTRB(12, 8, 12, 16),
        child: Column(
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Row(
              children: [
                IconButton(
                  tooltip: _playing ? 'Pause' : 'Play',
                  icon: Icon(_playing ? Icons.pause : Icons.play_arrow),
                  onPressed: () => _setPlaying(!_playing),
                ),
                IconButton(
                  tooltip: 'Back 50 ms',
                  icon: const Icon(Icons.skip_previous),
                  onPressed: () => _step(-50),
                ),
                IconButton(
                  tooltip: 'Forward 50 ms',
                  icon: const Icon(Icons.skip_next),
                  onPressed: () => _step(50),
                ),
                Expanded(
                  child: Slider(
                    value: time,
                    max: duration,
                    onChanged: _scrub,
                  ),
                ),
                SizedBox(
                  width: 92,
                  child: Text(
                    '${time.round()} / ${clip?.durationMs ?? 0} ms',
                    style: small,
                    textAlign: TextAlign.end,
                  ),
                ),
              ],
            ),
            Wrap(
              spacing: 8,
              runSpacing: 4,
              crossAxisAlignment: WrapCrossAlignment.center,
              children: [
                DropdownButton<String>(
                  value: hasClip ? _clipId : null,
                  isDense: true,
                  hint: const Text('No clips'),
                  items: <DropdownMenuItem<String>>[
                    for (final id in rig.clips.keys)
                      DropdownMenuItem<String>(value: id, child: Text(id)),
                  ],
                  onChanged: rig.clips.isEmpty
                      ? null
                      : (value) {
                          if (value != null) _selectClip(value);
                        },
                ),
                DropdownButton<int>(
                  value: _pixelScale,
                  isDense: true,
                  items: const <DropdownMenuItem<int>>[
                    DropdownMenuItem<int>(value: 1, child: Text('1x')),
                    DropdownMenuItem<int>(value: 2, child: Text('2x')),
                    DropdownMenuItem<int>(value: 3, child: Text('3x')),
                    DropdownMenuItem<int>(value: 4, child: Text('4x')),
                  ],
                  onChanged: (value) {
                    if (value != null) setState(() => _pixelScale = value);
                  },
                ),
                DropdownButton<double>(
                  value: _speed,
                  isDense: true,
                  items: const <DropdownMenuItem<double>>[
                    DropdownMenuItem<double>(value: 0.25, child: Text('0.25x')),
                    DropdownMenuItem<double>(value: 0.5, child: Text('0.5x')),
                    DropdownMenuItem<double>(value: 1, child: Text('1x')),
                    DropdownMenuItem<double>(value: 2, child: Text('2x')),
                    DropdownMenuItem<double>(value: 4, child: Text('4x')),
                  ],
                  onChanged: (value) {
                    if (value != null) _setSpeed(value);
                  },
                ),
                FilterChip(
                  label: const Text('Grid'),
                  selected: _showGrid,
                  onSelected: (value) => setState(() => _showGrid = value),
                ),
                FilterChip(
                  label: const Text('Pivots'),
                  selected: _showPivots,
                  onSelected: (value) => setState(() => _showPivots = value),
                ),
                FilterChip(
                  label: const Text('Hitboxes'),
                  selected: _showHitboxes,
                  onSelected: (value) => setState(() => _showHitboxes = value),
                ),
                FilterChip(
                  label: const Text('Layers'),
                  selected: _showLayers,
                  onSelected: (value) => setState(() => _showLayers = value),
                ),
                ActionChip(
                  label: Text(
                    switch (_background) {
                      1 => 'Dark',
                      2 => 'Light',
                      _ => 'Checker',
                    },
                  ),
                  onPressed: () =>
                      setState(() => _background = (_background + 1) % 3),
                ),
                ActionChip(
                  label: const Text('Throw'),
                  onPressed: _throwDefault,
                ),
                ActionChip(
                  label: const Text('Run route'),
                  onPressed: scene.ballPhase == BallPhase.none && !scene.isMoving
                      ? _runMovementRoute
                      : null,
                ),
                ActionChip(label: const Text('Reset'), onPressed: _reset),
                ActionChip(
                  label: const Text('Load rig'),
                  onPressed: _loadManifest,
                ),
                ActionChip(
                  label: const Text('Load atlas'),
                  onPressed: _loadAtlas,
                ),
                ActionChip(
                  label: const Text('Manifest'),
                  onPressed: _inspection == null
                      ? null
                      : _showManifestInspector,
                ),
              ],
            ),
            const SizedBox(height: 4),
            Text(
              '${scene.motion.name} · ball ${scene.ballPhase.name} · '
              'bounces ${scene.bounces} · pets ${scene.petCount} · '
              'facing ${scene.facing < 0 ? 'left' : 'right'} · '
              '$_sourceLabel'
              '${_loadStatus == null ? '' : ' · $_loadStatus'}',
              style: small,
            ),
            if (_showLayers) ...[
              const SizedBox(height: 6),
              for (final layer in rig.layers) _layerRow(layer, small),
            ],
            if (_log.isNotEmpty) ...[
              const SizedBox(height: 6),
              for (final line in _log)
                Text(line, style: small?.copyWith(fontFamily: 'monospace')),
            ],
          ],
        ),
      ),
    );
  }

  Widget _layerRow(LayerDefinition layer, TextStyle? style) {
    final visible = !_hiddenLayers.contains(layer.id);
    final opacity = _layerOpacity[layer.id] ?? 1.0;
    return Row(
      children: [
        Checkbox(
          value: visible,
          visualDensity: VisualDensity.compact,
          materialTapTargetSize: MaterialTapTargetSize.shrinkWrap,
          onChanged: (value) => setState(() {
            if (value ?? false) {
              _hiddenLayers.remove(layer.id);
            } else {
              _hiddenLayers.add(layer.id);
            }
          }),
        ),
        Expanded(
          child: Text(
            layer.parent == null ? layer.id : '${layer.id} ← ${layer.parent}',
            style: style,
            overflow: TextOverflow.ellipsis,
          ),
        ),
        SizedBox(
          width: 132,
          child: Slider(
            value: opacity,
            onChanged: (value) =>
                setState(() => _layerOpacity[layer.id] = value),
          ),
        ),
        SizedBox(
          width: 34,
          child: Text('${(opacity * 100).round()}', style: style),
        ),
      ],
    );
  }
